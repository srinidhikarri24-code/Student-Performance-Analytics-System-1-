import pandas as pd
import numpy as np

# Load student data
df = pd.read_csv('/content/student_marks_datasheet(1).csv')
df.columns = df.columns.str.strip()

subjects = ['Physics', 'Chemistry', 'Science']

# Calculate total and average marks
df['Total'] = df[subjects].sum(axis=1)
df['Average'] = df[subjects].mean(axis=1)

# Assign grade
def grade(avg):
    if avg >= 90:
        return 'A+'
    elif avg >= 80:
        return 'A'
    elif avg >= 70:
        return 'B'
    elif avg >= 60:
        return 'C'
    elif avg >= 50:
        return 'D'
    else:
        return 'E'

# Check pass or fail
def check_result(row):
    for subject in subjects:
        if row[subject] < 40:
            return 'Fail'
    return 'Pass'

df['Grade'] = df['Average'].apply(grade)
df['Result'] = df.apply(check_result, axis=1)
df.loc[df['Result'] == 'Fail', 'Grade'] = 'F'

# Display student report
print("STUDENT PERFORMANCE REPORT")
print(df.to_string(index=False))

# Class analysis
print("\nCLASS ANALYSIS")
print("Total students:", len(df))
print("Passed:", (df['Result'] == 'Pass').sum())
print("Failed:", (df['Result'] == 'Fail').sum())
print("Class average:", round(np.mean(df['Average']), 2))

# Subject-wise analysis
print("\nSUBJECT-WISE PERFORMANCE")
for subject in subjects:
    print(subject, "Average:", round(np.mean(df[subject]), 2))
    print("Highest marks:", df[subject].max())
    print("Lowest marks:", df[subject].min())

best_subject = max(subjects, key=lambda s: df[s].mean())
print("Best-performing subject:", best_subject)

# Top and lowest performers
print("\nTOP-PERFORMING STUDENT(S)")
print(df.loc[df['Average'] == df['Average'].max(),
             ['Name', 'Average', 'Grade']].to_string(index=False))

print("\nLOWEST-PERFORMING STUDENT(S)")
print(df.loc[df['Average'] == df['Average'].min(),
             ['Name', 'Average', 'Grade']].to_string(index=False))

# Save results
df.to_csv('/content/student_performance_results.csv', index=False)
print("\nResults saved successfully.")